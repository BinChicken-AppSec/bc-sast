#[tokio::test]
async fn legacy_metadata_is_reported_and_never_rewritten() {
    let root = cap_repo();
    let legacy = "<edmx:Edmx Version=\"1.0\" xmlns:edmx=\"http://schemas.microsoft.com/ado/2007/06/edmx\" xmlns:m=\"http://schemas.microsoft.com/ado/2007/08/dataservices/metadata\">\n  <edmx:DataServices m:DataServiceVersion=\"2.0\">\n    <Schema Namespace=\"CatalogService\" xmlns=\"http://schemas.microsoft.com/ado/2008/09/edm\">\n      <EntityType Name=\"Books\"><Property Name=\"ID\" Type=\"Edm.Int32\"/></EntityType>\n      <EntityContainer Name=\"Entities\"><EntitySet Name=\"Books\" EntityType=\"CatalogService.Books\"/></EntityContainer>\n    </Schema>\n  </edmx:DataServices>\n</edmx:Edmx>\n";
    write(root.path(), "webapp/localService/metadata.xml", legacy);
    let client = Client::new(Vec::new());
    let assurance = run_step(root.path(), &config(), &client).await;
    assert_eq!(client.calls(), 0);
    let outcome = only_odata(&assurance);
    assert_eq!(outcome.action, SpecAction::Reported);
    assert_eq!(outcome.version, Some(SpecVersion::Odata2));
    let codes: Vec<Code> = outcome.diagnostics_before.iter().map(|d| d.code).collect();
    assert_eq!(codes, [Code::LegacyVersion, Code::MissingKey]);
    assert!(outcome.gaps[0].contains("legacy"));
    assert_eq!(
        read(root.path(), "webapp/localService/metadata.xml"),
        legacy
    );
}

